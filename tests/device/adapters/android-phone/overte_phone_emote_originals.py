from copy import deepcopy
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import time

from adapters.native_feature_observation import exact,integer,need,number
from adapters.normal_feature_state import PrivateFeatureState,context
from feature_journeys.contract import identifier
from overte_phone_script_history import canonical,same

VERSION=1
LIMIT=1024*1024
BLOCK=128
MAX_FRAMES=1024


class PhoneEmoteOriginals:
    KINDS=frozenset({'sources','inputs'})
    def __init__(self,root,binding,run,role,guard,intent,*,kind='sources',monotonic=time.monotonic):
        self.root=Path(root);self.binding=deepcopy(context(binding));self.run=identifier(run);self.role=role
        need(role in ('primary','actor') and all(callable(value) for value in (guard,intent,monotonic)))
        need(kind in self.KINDS);self.kind=kind
        self.guard,self.intent,self.monotonic=guard,intent,monotonic;self.clock=None
        PrivateFeatureState(self.root/'emote-evidence-boundary.json')._parent()

    def now(self):
        value=self.monotonic();need(number(value,0,1e15) and (self.clock is None or value>=self.clock))
        self.clock=value;return value

    def bound(self,started):
        need(self.guard() is not False and self.now()-started<5)

    def original(self,value):
        exact(value,{'emoteOriginalVersion','kind','binding','runId','role','index','sha256','bytes','phase','file'})
        need(type(value['emoteOriginalVersion']) is int and value['emoteOriginalVersion']==VERSION
            and value['kind']==self.kind and same(context(value['binding']),self.binding) and value['runId']==self.run and value['role']==self.role
            and integer(value['index'],1,MAX_FRAMES) and type(value['sha256']) is str and re.fullmatch('[0-9a-f]{64}',value['sha256'])
            and integer(value['bytes'],2,LIMIT) and value['phase'] in ('planned','opened','saved'))
        if value['phase']=='planned':need(value['file'] is None)
        else:
            exact(value['file'],{'device','inode'})
            need(integer(value['file']['device'],0,2**64-1) and integer(value['file']['inode'],1,2**64-1))
        return value

    def path(self,value):
        self.original(value)
        path=self.root/('emote-frame-'+self.kind+'-'+self.run+'-'+self.role+'-'+format(value['index'],'04d')+'-'+value['sha256']+'.json')
        PrivateFeatureState(path)._parent();return path

    def file(self,path,descriptor,value):
        actual,current=os.fstat(descriptor),path.lstat()
        for row in (actual,current):
            need(stat.S_ISREG(row.st_mode) and row.st_nlink==1 and row.st_size<=LIMIT
                and (os.name=='nt' or row.st_uid==os.geteuid() and stat.S_IMODE(row.st_mode)==0o600))
        need((actual.st_dev,actual.st_ino)==(current.st_dev,current.st_ino)==(value['file']['device'],value['file']['inode']))

    def read(self,value):
        started=self.now();self.bound(started);path=self.path(value);need(value['phase'] in ('opened','saved'))
        descriptor=os.open(path,os.O_RDONLY|getattr(os,'O_NOFOLLOW',0)|getattr(os,'O_NONBLOCK',0))
        with os.fdopen(descriptor,'rb') as stream:
            self.file(path,stream.fileno(),value);raw=stream.read(LIMIT+1);self.file(path,stream.fileno(),value)
        need(len(raw)==value['bytes'] and hashlib.sha256(raw).hexdigest()==value['sha256'])
        body=json.loads(raw.decode('utf-8'));need(canonical(body)==raw)
        exact(body,{'emoteFrameVersion','kind','binding','runId','role','index','frame'})
        need(type(body['emoteFrameVersion']) is int and body['emoteFrameVersion']==VERSION and same(body['binding'],self.binding)
            and body['kind']==self.kind and body['runId']==self.run and body['role']==self.role and type(body['index']) is int and body['index']==value['index']
            and type(body['frame']) is dict)
        # json.loads created this graph exclusively for this read. Returning it
        # cannot alias another read or mutate the immutable original bytes.
        self.bound(started);return body['frame']

    def diagnostic(self,value):
        """Retain actual partial bytes/metadata without adopting a saved frame."""
        started=self.now();self.bound(started);path=self.path(value)
        if value['phase']=='planned':
            try:path.lstat()
            except FileNotFoundError:self.bound(started);return None
            need(False)
        if value['phase']=='saved':self.read(value);self.bound(started);return None
        descriptor=os.open(path,os.O_RDONLY|getattr(os,'O_NOFOLLOW',0)|getattr(os,'O_NONBLOCK',0))
        with os.fdopen(descriptor,'rb') as stream:
            self.file(path,stream.fileno(),value);before=os.fstat(stream.fileno())
            raw=stream.read(LIMIT+1);self.file(path,stream.fileno(),value)
            after,current=os.fstat(stream.fileno()),path.lstat()
            signature=lambda row:(row.st_dev,row.st_ino,row.st_size,row.st_mtime_ns,row.st_ctime_ns)
            need(signature(before)==signature(after)==signature(current) and len(raw)==after.st_size<=value['bytes'])
            need(all(integer(stamp,0,2**64-1) for stamp in (after.st_mtime_ns,after.st_ctime_ns)))
        result=dict(originalDiagnosticVersion=1,name=path.name,bytes=len(raw),sha256=hashlib.sha256(raw).hexdigest(),
            file=dict(device=after.st_dev,inode=after.st_ino,modifiedNs=after.st_mtime_ns,changedNs=after.st_ctime_ns))
        self.bound(started);return result

    def write(self,index,frame):
        started=self.now();self.bound(started);need(integer(index,1,MAX_FRAMES) and type(frame) is dict)
        body=dict(emoteFrameVersion=VERSION,kind=self.kind,binding=self.binding,runId=self.run,role=self.role,index=index,frame=frame)
        raw=canonical(body);need(2<=len(raw)<=LIMIT)
        value=dict(emoteOriginalVersion=VERSION,kind=self.kind,binding=deepcopy(self.binding),runId=self.run,role=self.role,index=index,
            sha256=hashlib.sha256(raw).hexdigest(),bytes=len(raw),phase='planned',file=None)
        path=self.path(value);need(self.intent('original',deepcopy(value)) is not False);self.bound(started)
        descriptor=os.open(path,os.O_WRONLY|os.O_CREAT|os.O_EXCL|getattr(os,'O_NOFOLLOW',0),0o600)
        with os.fdopen(descriptor,'wb') as stream:
            info=os.fstat(stream.fileno());value.update(phase='opened',file=dict(device=info.st_dev,inode=info.st_ino))
            self.file(path,stream.fileno(),value);need(self.intent('original',deepcopy(value)) is not False);self.bound(started)
            need(stream.write(raw)==len(raw));stream.flush();os.fsync(stream.fileno());self.file(path,stream.fileno(),value)
            self.bound(started)
        need(same(self.read(value),frame));self.bound(started)
        value['phase']='saved';need(self.intent('original',deepcopy(value)) is not False);self.bound(started)
        return self.compact(value)

    def resume_write(self,index,frame,value):
        """Finish exact owned archival bytes, retaining every existing prefix.

        The caller supplies an independently validated frozen archival record,
        never an expected product result. Existing bytes cannot be overwritten.
        """
        started=self.now();self.bound(started);self.original(value)
        need(integer(index,1,MAX_FRAMES) and type(frame) is dict)
        body=dict(emoteFrameVersion=VERSION,kind=self.kind,binding=self.binding,runId=self.run,role=self.role,index=index,frame=frame)
        raw=canonical(body);need(value['index']==index and value['bytes']==len(raw)<=LIMIT
            and value['sha256']==hashlib.sha256(raw).hexdigest())
        value=deepcopy(value);path=self.path(value)
        if value['phase']=='saved':need(same(self.read(value),frame));self.bound(started);return self.compact(value)
        if value['phase']=='planned':
            need(self.diagnostic(value) is None)
            descriptor=os.open(path,os.O_RDWR|os.O_CREAT|os.O_EXCL|getattr(os,'O_NOFOLLOW',0),0o600)
        else:descriptor=os.open(path,os.O_RDWR|getattr(os,'O_NOFOLLOW',0)|getattr(os,'O_NONBLOCK',0))
        with os.fdopen(descriptor,'r+b') as stream:
            if value['phase']=='planned':
                info=os.fstat(stream.fileno());value.update(phase='opened',file=dict(device=info.st_dev,inode=info.st_ino))
                self.file(path,stream.fileno(),value);need(self.intent('original',deepcopy(value)) is not False);self.bound(started)
            self.file(path,stream.fileno(),value);before=os.fstat(stream.fileno())
            prefix=stream.read(LIMIT+1);self.file(path,stream.fileno(),value);after=os.fstat(stream.fileno())
            signature=lambda row:(row.st_dev,row.st_ino,row.st_size,row.st_mtime_ns,row.st_ctime_ns)
            need(signature(before)==signature(after) and len(prefix)==after.st_size<=len(raw) and raw.startswith(prefix))
            self.bound(started);remaining=raw[len(prefix):]
            need(stream.write(remaining)==len(remaining));stream.flush();os.fsync(stream.fileno())
            self.file(path,stream.fileno(),value);self.bound(started)
        need(same(self.read(value),frame));self.bound(started)
        value['phase']='saved';need(self.intent('original',deepcopy(value)) is not False);self.bound(started)
        return self.compact(value)

    def compact(self,value):
        self.original(value);need(value['phase']=='saved')
        return dict(index=value['index'],sha256=value['sha256'],bytes=value['bytes'],**value['file'])

    def expand(self,value):
        exact(value,{'index','sha256','bytes','device','inode'})
        original=dict(emoteOriginalVersion=VERSION,kind=self.kind,binding=self.binding,runId=self.run,role=self.role,
            index=value['index'],sha256=value['sha256'],bytes=value['bytes'],phase='saved',file=dict(device=value['device'],inode=value['inode']))
        return self.original(original)

    @staticmethod
    def manifest_reference(value):
        exact(value,{'block','count','sha256','bytes'})
        need(integer(value['block'],1,MAX_FRAMES//BLOCK) and integer(value['count'],1,BLOCK)
            and type(value['sha256']) is str and re.fullmatch('[0-9a-f]{64}',value['sha256'])
            and integer(value['bytes'],2,65535))

    def manifest_path(self,value):
        self.manifest_reference(value)
        return self.root/('emote-index-'+self.kind+'-'+self.run+'-'+self.role+'-'+str(value['block'])+'-'+str(value['count'])+'-'+value['sha256']+'.json')

    def manifest(self,value):
        started=self.now();self.bound(started);store=PrivateFeatureState(self.manifest_path(value));body=store.read()
        need(body is not None);raw=canonical(body)
        need(len(raw)==value['bytes'] and hashlib.sha256(raw).hexdigest()==value['sha256'])
        exact(body,{'emoteManifestVersion','kind','binding','runId','role','block','entries'})
        need(type(body['emoteManifestVersion']) is int and body['emoteManifestVersion']==VERSION
            and body['kind']==self.kind and same(body['binding'],self.binding) and body['runId']==self.run and body['role']==self.role
            and type(body['block']) is int and body['block']==value['block'] and type(body['entries']) is list
            and len(body['entries'])==value['count'])
        for offset,row in enumerate(body['entries'],1):
            self.expand(row);need(row['index']==(value['block']-1)*BLOCK+offset)
        self.bound(started);return deepcopy(body['entries'])

    def append(self,references,original):
        started=self.now();self.bound(started);expanded=self.expand(original);index=expanded['index']
        need(type(references) is list and len(references)<=MAX_FRAMES//BLOCK)
        self.read(expanded)
        for number_,reference in enumerate(references,1):
            self.manifest_reference(reference);need(reference['block']==number_
                and (number_==len(references) or reference['count']==BLOCK))
        block=(index-1)//BLOCK+1;offset=(index-1)%BLOCK+1
        entries=[];result=deepcopy(references)
        if offset==1:need(len(result)==block-1 and (not result or result[-1]['count']==BLOCK))
        else:
            need(len(result)==block and result[-1]['block']==block and result[-1]['count']==offset-1)
            entries=self.manifest(result[-1]);result.pop()
        entries.append(deepcopy(original))
        body=dict(emoteManifestVersion=VERSION,kind=self.kind,binding=self.binding,runId=self.run,role=self.role,block=block,entries=entries)
        raw=canonical(body);reference=dict(block=block,count=len(entries),sha256=hashlib.sha256(raw).hexdigest(),bytes=len(raw))
        self.manifest_reference(reference)
        intent=dict(emoteManifestVersion=VERSION,reference=reference,phase='planned')
        need(self.intent('manifest',deepcopy(intent)) is not False);self.bound(started)
        store=PrivateFeatureState(self.manifest_path(reference));store.write(body,None)
        need(same(self.manifest(reference),entries));self.bound(started)
        intent['phase']='saved';need(self.intent('manifest',deepcopy(intent)) is not False);self.bound(started)
        result.append(reference);return result

    def resume_manifest(self,references,original,intent):
        """Finish this exact durable manifest intent; never adopt another index."""
        if intent is None:return self.append(references,original)
        started=self.now();self.bound(started);expanded=self.expand(original);index=expanded['index']
        need(type(references) is list and len(references)<=MAX_FRAMES//BLOCK)
        exact(intent,{'emoteManifestVersion','reference','phase'})
        need(type(intent['emoteManifestVersion']) is int and intent['emoteManifestVersion']==VERSION and intent['phase'] in ('planned','saved'))
        self.manifest_reference(intent['reference']);self.read(expanded)
        block=(index-1)//BLOCK+1;offset=(index-1)%BLOCK+1;result=deepcopy(references)
        for count,reference in enumerate(result,1):
            self.manifest_reference(reference);need(reference['block']==count and (count==len(result) or reference['count']==BLOCK))
        if offset==1:
            need(len(result)==block-1 and (not result or result[-1]['count']==BLOCK));entries=[]
        else:
            need(len(result)==block and result[-1]['block']==block and result[-1]['count']==offset-1)
            entries=self.manifest(result.pop())
        entries.append(deepcopy(original))
        body=dict(emoteManifestVersion=VERSION,kind=self.kind,binding=self.binding,runId=self.run,role=self.role,block=block,entries=entries)
        raw=canonical(body);reference=dict(block=block,count=len(entries),sha256=hashlib.sha256(raw).hexdigest(),bytes=len(raw))
        need(same(reference,intent['reference']));self.bound(started)
        store=PrivateFeatureState(self.manifest_path(reference));actual=store.read()
        if actual is None:
            need(intent['phase']=='planned');store.write(body,None)
        need(same(self.manifest(reference),entries));self.bound(started)
        if intent['phase']=='planned':need(self.intent('manifest',dict(intent,phase='saved')) is not False)
        self.bound(started);result.append(reference);return result

    def restore(self,references,revision):
        need(type(references) is list and len(references)<=MAX_FRAMES//BLOCK and integer(revision,0,MAX_FRAMES))
        frames=[]
        for block,reference in enumerate(references,1):
            self.manifest_reference(reference);need(reference['block']==block and (block==len(references) or reference['count']==BLOCK))
            for row in self.manifest(reference):frames.append(self.read(self.expand(row)))
        need(len(frames)==revision);return frames
